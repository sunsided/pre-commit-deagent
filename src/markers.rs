//! Recognizing AI coding agent markers in commit messages and identities.

/// Exact email addresses agents use for themselves.
const AGENT_EMAILS: &[&str] = &[
    "noreply@anthropic.com",
    "claude@anthropic.com",
    "codex@openai.com",
    "noreply@openai.com",
    "cursoragent@cursor.com",
    "noreply@aider.chat",
];

/// Product names; matched against GitHub bot accounts and "Generated with ..." lines.
const AGENT_NAMES: &[&str] = &[
    "claude", "codex", "copilot", "cursor", "gemini", "jules", "devin", "aider", "openai",
];

/// URL fragments of agent session / task links.
const SESSION_URLS: &[&str] = &[
    "claude.ai/code/",
    "chatgpt.com/codex/tasks/",
    "jules.google.com/task/",
];

/// Whether `Name <email>` belongs to an AI agent. Decided by email only, so a human
/// co-author who happens to be called Claude is kept.
pub fn is_agent_ident(ident: &str) -> bool {
    let email = match (ident.rfind('<'), ident.rfind('>')) {
        (Some(a), Some(b)) if a < b => ident[a + 1..b].trim().to_lowercase(),
        _ => return false,
    };
    if AGENT_EMAILS.contains(&email.as_str()) {
        return true;
    }
    // GitHub noreply: `<id>+<login>@users.noreply.github.com`
    let Some(login) = email.strip_suffix("@users.noreply.github.com") else {
        return false;
    };
    let login = login.rsplit('+').next().unwrap_or(login);
    login == "copilot"
        || (login.ends_with("[bot]") && AGENT_NAMES.iter().any(|n| login.contains(n)))
}

fn is_marker_line(line: &str) -> bool {
    let lower = line.trim().to_lowercase();
    if let Some((key, value)) = lower.split_once(':')
        && key.trim() == "co-authored-by"
    {
        return is_agent_ident(value);
    }
    if SESSION_URLS.iter().any(|u| lower.contains(u)) {
        return true;
    }
    // e.g. "🤖 Generated with [Claude Code](https://claude.com/claude-code)"
    let text = lower.trim_start_matches(|c: char| !c.is_alphanumeric());
    (text.starts_with("generated with ") || text.starts_with("generated by "))
        && AGENT_NAMES.iter().any(|n| text.contains(n))
}

/// Returns the message without marker lines, and the removed lines.
/// The message is returned unchanged if nothing was removed.
pub fn strip_markers(message: &str) -> (String, Vec<String>) {
    let (removed, kept): (Vec<&str>, Vec<&str>) = message.lines().partition(|l| is_marker_line(l));
    if removed.is_empty() {
        return (message.to_string(), vec![]);
    }
    let mut out = String::new();
    for line in kept {
        // drop blank lines the removed block leaves behind
        if line.trim().is_empty() && (out.is_empty() || out.ends_with("\n\n")) {
            continue;
        }
        out.push_str(line);
        out.push('\n');
    }
    let out = format!("{}\n", out.trim_end());
    (out, removed.into_iter().map(String::from).collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn strips_claude_code_footer() {
        let msg = "Fix bug\n\nLonger body.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-Authored-By: Claude Opus 4.5 <noreply@anthropic.com>\n";
        let (out, removed) = strip_markers(msg);
        assert_eq!(out, "Fix bug\n\nLonger body.\n");
        assert_eq!(removed.len(), 2);
    }

    #[test]
    fn strips_session_link_and_keeps_human_trailers() {
        let msg = "Add thing\n\nhttps://claude.ai/code/session_011CUabc\n\nCo-authored-by: Claude Monet <claude@monet.fr>\nCo-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>\nSigned-off-by: Jane <jane@x.org>\n";
        let (out, removed) = strip_markers(msg);
        assert_eq!(
            out,
            "Add thing\n\nCo-authored-by: Claude Monet <claude@monet.fr>\nSigned-off-by: Jane <jane@x.org>\n"
        );
        assert_eq!(removed.len(), 2);
    }

    #[test]
    fn clean_message_is_untouched() {
        let msg = "Subject\n\n\nbody mentions claude and was generated by hand\n";
        assert_eq!(strip_markers(msg), (msg.to_string(), vec![]));
    }

    #[test]
    fn agent_idents() {
        assert!(is_agent_ident("Claude <noreply@anthropic.com>"));
        assert!(is_agent_ident("Cursor Agent <cursoragent@cursor.com>"));
        assert!(is_agent_ident(
            "claude[bot] <209825114+claude[bot]@users.noreply.github.com>"
        ));
        assert!(!is_agent_ident("Claude <claude@example.com>"));
        assert!(!is_agent_ident(
            "dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>"
        ));
        assert!(!is_agent_ident(
            "claudette <1+claudette@users.noreply.github.com>"
        ));
    }
}
